#!/usr/bin/env node
/**
 * Concatenate the browser-half fragments into the single `client.js` module the
 * Harness ModuleLoader evaluates. Run: node knowledge-board/build.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const pkg = JSON.parse(fs.readFileSync(path.join(here, 'package.json'), 'utf8'))
const parts = [
  '01-style.js',
  '02-util.js',
  '03-charts.js',
  '04-overview.js',
  '05-library.js',
  '06-map.js',
  '07-todos.js',
  '08-settings.js',
  '09-panel.js',
]
let body = ''
for (const part of parts) {
  const text = fs.readFileSync(path.join(here, 'src', part), 'utf8')
  body += `\n/* ===================== ${part} ===================== */\n` + text + '\n'
}

const out = `/* Generated by build.mjs — edit src/*.js, then rebuild. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const React = require('react')
    const h = React.createElement
    const { useState, useEffect, useMemo, useRef, useCallback } = React
${body}
  },
})
`

fs.writeFileSync(path.join(here, 'client.js'), out)
console.log('client.js', (Buffer.byteLength(out) / 1024).toFixed(1) + ' KB')
